// v17.2 ScreenCaptureKit Stream
@interface DEFrameSink : NSObject<SCStreamOutput>
@property (atomic) CVPixelBufferRef latest;
@end
@implementation DEFrameSink
- (instancetype)init { if ((self=[super init])) _latest=nullptr; return self; }
- (void)dealloc { if (_latest) CFRelease(_latest); }
- (void)stream:(SCStream*)s didOutputSampleBuffer:(CMSampleBufferRef)sb ofType:(SCStreamOutputType)type {
    if (type != SCStreamOutputTypeScreen) return;
    CVPixelBufferRef pb=(CVPixelBufferRef)CMSampleBufferGetImageBuffer(sb); if(!pb) return;
    CVPixelBufferRetain(pb);
    CVPixelBufferRef old=_latest; _latest=pb; if(old) CFRelease(old);
}
@end

struct Capture {
    SCStream* stream=nil; DEFrameSink* sink=nil; bool started=false;
    bool start() {
        if (started) return true;
        __block BOOL ok=NO; __block SCShareableContent* content=nil;
        dispatch_semaphore_t sem=dispatch_semaphore_create(0);
        [SCShareableContent getShareableContentWithCompletionHandler:^(SCShareableContent* c, NSError* e){
            content=c; ok=(c && !e && c.displays.count>0); dispatch_semaphore_signal(sem);
        }];
        dispatch_semaphore_wait(sem, DISPATCH_TIME_FOREVER);
        if(!ok) return false;

        SCDisplay* d=content.displays.firstObject;
        SCContentFilter* filter=[[SCContentFilter alloc] initWithDisplay:d excludingApplications:@[] exceptingWindows:@[]];

        SCStreamConfiguration* cfg=[SCStreamConfiguration new];
        cfg.showsCursor=NO; cfg.capturesAudio=NO; cfg.pixelFormat=kCVPixelFormatType_32BGRA;
        cfg.width=d.width; cfg.height=d.height;

        sink=[DEFrameSink new];
        stream=[[SCStream alloc] initWithFilter:filter configuration:cfg delegate:nil];

        NSError* err=nil;
        if(![stream addStreamOutput:sink type:SCStreamOutputTypeScreen
             sampleHandlerQueue:dispatch_get_global_queue(QOS_CLASS_USER_INTERACTIVE,0) error:&err]) return false;

        __block BOOL startedOK=NO; dispatch_semaphore_t sem2=dispatch_semaphore_create(0);
        [stream startCaptureWithCompletionHandler:^(NSError* e){ startedOK=(e==nil); dispatch_semaphore_signal(sem2);}];
        dispatch_semaphore_wait(sem2, DISPATCH_TIME_FOREVER);
        started = startedOK;
        return startedOK;
    }

    cv::Mat latest_cropped_downscaled() {
        CVPixelBufferRef pb = sink ? sink.latest : nil;
        if(!pb) return {};

        // Retain the buffer to prevent it from being released while we use it
        CFRetain(pb);

        // Try to lock - if it fails, the buffer is invalid
        CVReturn lockResult = CVPixelBufferLockBaseAddress(pb, kCVPixelBufferLock_ReadOnly);
        if(lockResult != kCVReturnSuccess) {
            CFRelease(pb);
            return {};
        }

        size_t W=CVPixelBufferGetWidth(pb), H=CVPixelBufferGetHeight(pb), stride=CVPixelBufferGetBytesPerRow(pb);
        uint8_t* base=(uint8_t*)CVPixelBufferGetBaseAddress(pb);
        if(!base){
            CVPixelBufferUnlockBaseAddress(pb, kCVPixelBufferLock_ReadOnly);
            CFRelease(pb);
            return {};
        }
        cv::Mat bgra((int)H,(int)W,CV_8UC4,base,stride);

        CGRect r=g_windowRect; // TOP-left coordinate rect
        int x=std::max(0,(int)r.origin.x), y=std::max(0,(int)r.origin.y);
        int cw=std::min<int>((int)r.size.width,(int)W-x);
        int ch=std::min<int>((int)r.size.height,(int)H-y);

        cv::Mat crop;
        if (cw>1 && ch>1) crop = bgra(cv::Rect(x,y,cw,ch)).clone();
        CVPixelBufferUnlockBaseAddress(pb, kCVPixelBufferLock_ReadOnly);
        CFRelease(pb);

        if (crop.empty()) return {};
        cv::Mat bgr; cv::cvtColor(crop,bgr,cv::COLOR_BGRA2BGR);
        cv::resize(bgr,bgr,cv::Size(RADAR_WIDTH,RADAR_HEIGHT),0,0,cv::INTER_LINEAR);
        return bgr;
    }
};
