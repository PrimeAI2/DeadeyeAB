static void release_mouse_now() {
    CGPoint p = currentMouse();
    release_mouse(); // Use our v14.2 function
}
static CGEventRef tap_cb(CGEventTapProxy, CGEventType type, CGEventRef e, void*){
    if(type==kCGEventTapDisabledByTimeout || type==kCGEventTapDisabledByUserInput){
        if(g_tap) CGEventTapEnable(g_tap,true);
        return e;
    }
    if(type==kCGEventKeyDown){
        auto code=(CGKeyCode)CGEventGetIntegerValueField(e,kCGKeyboardEventKeycode);
        if(code==kVK_ANSI_X){
            g_quit.store(true);
            // v17.2's `[NSApp terminate:nil]` is cleaner, let's use it
            dispatch_async(dispatch_get_main_queue(), ^{ release_mouse_now(); [NSApp terminate:nil]; });
        }
    }
    return e;
}
static void start_key_thread(){
    g_tap = CGEventTapCreate(kCGSessionEventTap, kCGHeadInsertEventTap,
                               kCGEventTapOptionListenOnly, CGEventMaskBit(kCGEventKeyDown),
                               tap_cb, nullptr);
    if(!g_tap) return;
    g_tapSrc = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, g_tap, 0);
    std::thread([](){
        @autoreleasepool {
            CFRunLoopRef rl=CFRunLoopGetCurrent();
            CFRunLoopAddSource(rl, g_tapSrc, kCFRunLoopCommonModes);
            CGEventTapEnable(g_tap, true);
            CFRunLoopRun();
        }
    }).detach();
}
static void stop_kill_switch(){
    if(g_tap) CGEventTapEnable(g_tap,false);
    if(g_tapSrc){ CFRunLoopSourceInvalidate(g_tapSrc); CFRelease(g_tapSrc); g_tapSrc=nullptr; }
    if(g_tap){ CFMachPortInvalidate(g_tap); CFRelease(g_tap); g_tap=nullptr; }
}


