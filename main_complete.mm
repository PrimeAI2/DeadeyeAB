// This is the 45Hz bot logic loop, moved from main()
void start_bot_logic_timer() {
    log_line("Startup OK. Cannon holding. Starting bot logic loop...");

    // [v14.2] Bot logic state
    __block cv::Mat debugMat(RADAR_HEIGHT, RADAR_WIDTH, CV_8UC4, cv::Scalar(0,0,0,255));
    __block auto last_logic_time = std::chrono::steady_clock::now();
    __block long frame_count = 0;

    const double bot_fps = 45.0;
    g_bot_logic_timer = dispatch_source_create(DISPATCH_SOURCE_TYPE_TIMER, 0, 0, dispatch_get_main_queue());
    dispatch_source_set_timer(g_bot_logic_timer, DISPATCH_TIME_NOW, (uint64_t)( (1.0/bot_fps) * NSEC_PER_SEC), (uint64_t)(0.01 * NSEC_PER_SEC));
    dispatch_source_set_event_handler(g_bot_logic_timer, ^{
        @autoreleasepool {
            if (g_quit.load()) {
                dispatch_source_cancel(g_bot_logic_timer);
                return;
            }
            
            // --- v17.2: UI / Window Tracking ---
            WindowInfo cur = find_window_info(WINDOW_TITLE.c_str());
            if(cur.valid && (cur.rect.origin.x != g_windowRect.origin.x || cur.rect.origin.y != g_windowRect.origin.y)) {
                g_windowRect = cur.rect;
                center_overlay_on_window();
                ensure_debug_window_left_of_mirror();
            }

            // --- v14.2: Bot Logic (All ported) ---
            double ts = nowSec();
            auto now = std::chrono::steady_clock::now();
            float dt = std::chrono::duration<float>(now - last_logic_time).count();
            last_logic_time = now;
            
            cv::Mat currentFrameCV = g_cap.latest_cropped_downscaled(); 
            if(currentFrameCV.empty()) return;

            float obs_x = track_cannon_live(currentFrameCV);
            if(obs_x>=0) g_observed_cannon_x_rel = obs_x;

            id<MTLTexture> curTex = cv_to_texture(currentFrameCV);
            if(g_lastFrameTexture){ 
                run_radar_on_pair(curTex, g_lastFrameTexture); 
            }
            MTLRegion region=MTLRegionMake2D(0,0,RADAR_WIDTH,RADAR_HEIGHT);
            [g_debugTexture getBytes:debugMat.data bytesPerRow:RADAR_WIDTH*4 fromRegion:region mipmapLevel:0];

            // radar output is BGRA, bot needs BGR for some CV ops
            cv::cvtColor(debugMat, debugMat, cv::COLOR_BGRA2BGR); 

            update_rock_database(debugMat, ts, dt); 
            update_bullets(dt); 
            check_bullet_hits();

            {
                std::lock_guard<std::mutex> lk(g_log_mutex);
                for(auto const& [id,r]: g_rock_database){
                    g_rock_log<<ts<<","<<id<<","<<r.center.x<<","<<r.center.y<<","
                             <<r.velocity.x<<","<<r.velocity.y<<","<<r.hp<<","
                             <<r.original_hp<<","<<r.time_to_ground<<","<<r.predicted_x<<"\n";
                }
            }

            float cannon_x = g_observed_cannon_x_rel;
            BotDecision dec = decide(cannon_x);

            bool imminent=false;
            for(const auto& [id,r]: g_rock_database){
                if(r.time_to_ground<PANIC_TIME && std::abs(r.predicted_x-cannon_x)<CANNON_WIDTH){ 
                    imminent=true; break; 
                }
            }

            {
                std::lock_guard<std::mutex> lk(g_log_mutex);
                g_bot_log<<ts<<","<<cannon_x<<","<<g_rock_database.size()<<","
                        <<dec.priority<<","<<dec.strategy<<","<<dec.decision<<","
                        <<dec.target_x_rel<<"\n";
            }

            move_mouse(g_windowRect.origin.x + dec.target_x_rel, g_cannon_y_abs);
            keep_mouse_held();
            ensure_drag_control(cannon_x, dec.target_x_rel, imminent);

            std::string status_str = "LIVE: " + dec.strategy + " | " + dec.decision;
            debug_draw_and_show(debugMat, status_str);
            
            g_lastFrameTexture = curTex; // ARC will handle the old one
            frame_count++;
            
            if(frame_count%60==0) {
                log_line("[Frame "+std::to_string(frame_count)+
                         "] Rocks: "+std::to_string(g_rock_database.size())+
                         " | "+dec.strategy+" | "+dec.decision);
            }
        } // end @autoreleasepool
    });
    dispatch_resume(g_bot_logic_timer);
}


// This is the new, NON-BLOCKING startup sequence
void start_startup_sequence_timer() {
    log_line("=== ASYNC STARTUP SEQUENCE ===");
    
    // This timer runs at 10Hz to check for buttons/cannon
    const double startup_fps = 10.0;
    g_startup_timer = dispatch_source_create(DISPATCH_SOURCE_TYPE_TIMER, 0, 0, dispatch_get_main_queue());
    dispatch_source_set_timer(g_startup_timer, DISPATCH_TIME_NOW, (uint64_t)( (1.0/startup_fps) * NSEC_PER_SEC), (uint64_t)(0.01 * NSEC_PER_SEC));
    dispatch_source_set_event_handler(g_startup_timer, ^{
        @autoreleasepool {
            if (g_quit.load()) {
                dispatch_source_cancel(g_startup_timer);
                return;
            }

            // Always update window rect
            WindowInfo info = find_window_info(WINDOW_TITLE.c_str());
            if(info.valid) g_windowRect = info.rect;
            else {
                log_line("Startup failed: Window lost");
                g_quit.store(true);
                return;
            }
            
            // Always get latest frame
            cv::Mat f = g_cap.latest_cropped_downscaled();
            if (f.empty()) return; // Try again next tick

            // --- STATE MACHINE ---
            
            if (g_startupState == StartupState::LookingForButton) {
                auto btns = find_orange_buttons(f);
                debug_draw_and_show(cv::Mat(), "Looking for 'Play' (2nd)...");

                if (btns.size() >= 2) {
                    g_foundButtonRect = btns[1].r;  // Get and save the second button
                    
                    int fx = g_foundButtonRect.x + (int)(g_foundButtonRect.width * BUTTON_X_BIAS_FRAC); // 0.5
                    int fy = g_foundButtonRect.y + g_foundButtonRect.height/2 + (int)BUTTON_Y_OFFSET_PX; // 0.0
                    CGFloat sx = wx(fx);
                    CGFloat sy = wy_event(fy);

                    log_line("Clicking 2nd button (v14.2 Centered) at screen(" + std::to_string((int)sx) + "," + std::to_string((int)sy) + ")");
                    
                    activate_app_by_pid(info.pid);
                    move_mouse(sx, sy);
                    std::this_thread::sleep_for(120ms); // Short sleep for mouse move is ok
                    click_once(sx, sy);
                    
                    // Transition to next state
                    g_startupState = StartupState::ButtonClicked;
                    g_startupRetryCheckTime = nowSec() + 0.3; // Wait 300ms before checking for retry
                }
                // If button not found, just wait for next tick

            } else if (g_startupState == StartupState::ButtonClicked) {
                if (nowSec() < g_startupRetryCheckTime) return; // Wait for retry time to elapse

                auto buttons2 = find_orange_buttons(f);
                bool still_there = false;
                if(buttons2.size() >= 2) {
                    std::sort(buttons2.begin(), buttons2.end(), [](auto&A,auto&B){return A.c.y < B.c.y;});
                    if(std::abs(buttons2[1].r.x - g_foundButtonRect.x) < 10 &&
                       std::abs(buttons2[1].r.y - g_foundButtonRect.y) < 10) {
                        still_there = true;
                    }
                }
                
                if(still_there) {
                    int fx = g_foundButtonRect.x + (int)(g_foundButtonRect.width * BUTTON_X_BIAS_FRAC);
                    int fy = g_foundButtonRect.y + g_foundButtonRect.height/2 + (int)BUTTON_Y_OFFSET_PX;
                    CGFloat sx = wx(fx);
                    CGFloat sy = wy_event(fy);
                    
                    log_line("Button still present, retry click at (" + std::to_string((int)sx) + "," + std::to_string((int)sy) + ")");
                    move_mouse(sx, sy);
                    std::this_thread::sleep_for(100ms);
                    click_once(sx, sy);
                }
                
                // Transition to next state
                g_startupState = StartupState::LookingForCannon;
                log_line("Waiting for transition to game screen...");

            } else if (g_startupState == StartupState::LookingForCannon) {
                cv::Point cannon = find_cannon_start(f);
                debug_draw_and_show(cv::Mat(), "Searching for cannon…");

                if (cannon.x >= 0) {
                    // --- FOUND CANNON! ---
                    CGFloat cannon_abs_x = wx(cannon.x);
                    CGFloat cannon_abs_y = wy_event(cannon.y);
                    g_cannon_y_abs = cannon_abs_y; // Save the absolute Y
                    
                    click_and_hold(cannon_abs_x, cannon_abs_y);
                    
                    g_observed_cannon_x_rel = cannon.x;
                    g_last_observed_x_rel   = cannon.x;
                    
                    debug_draw_and_show(cv::Mat(), "CANNON: HOLDING");
                    
                    // --- Transition to DONE ---
                    g_startupState = StartupState::Done;
                    log_line("Startup OK. Cannon holding.");

                    // Stop this startup timer
                    dispatch_source_cancel(g_startup_timer);
                    
                    // --- START THE REAL BOT LOGIC LOOP ---
                    start_bot_logic_timer();
                }
                // If cannon not found, just wait for next tick
            }
            
        } // end @autoreleasepool
    });
    dispatch_resume(g_startup_timer);
}

