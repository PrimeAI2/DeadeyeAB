bool init_metal_pipeline(const std::string& execDir){
    std::string metalPath=execDir+"/RockGame.metal";
    if(!std::filesystem::exists(metalPath)) metalPath=execDir+"/../RockGame.metal";

    g_device=MTLCreateSystemDefaultDevice(); if(!g_device){ std::cerr<<"FATAL: no Metal device\n"; return false; }
    g_commandQueue=[g_device newCommandQueue]; if(!g_commandQueue){ std::cerr<<"FATAL: no command queue\n"; return false; }

    NSError* error=nil; std::ifstream mf(metalPath);
    if(!mf.is_open()){ std::cerr<<"FATAL: Could not open shader: "<<metalPath<<"\n"; return false; }
    std::string srcStr((std::istreambuf_iterator<char>(mf)), std::istreambuf_iterator<char>());
    NSString* src=[[NSString alloc] initWithBytes:srcStr.data() length:srcStr.size() encoding:NSUTF8StringEncoding];

    id<MTLLibrary> radarLibrary=[g_device newLibraryWithSource:src options:nil error:&error];
    if(!radarLibrary){ std::cerr<<"FATAL: shader compile failed\n"; return false; }
    id<MTLFunction> radarFunction=[radarLibrary newFunctionWithName:@"rockgameRadar"];
    if(!radarFunction){ std::cerr<<"FATAL: function rockgameRadar missing\n"; return false; }
    g_radarPipeline=[g_device newComputePipelineStateWithFunction:radarFunction error:&error];
    if(!g_radarPipeline){ std::cerr<<"FATAL: pipeline create failed\n"; return false; }

    MTLTextureDescriptor* td=[MTLTextureDescriptor texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm width:RADAR_WIDTH height:RADAR_HEIGHT mipmapped:NO];
    td.usage=MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite; g_debugTexture=[g_device newTextureWithDescriptor:td];

    g_constantsBuffer=[g_device newBufferWithLength:sizeof(int)*3 options:MTLResourceStorageModeShared];
    int* c=(int*)[g_constantsBuffer contents]; c[0]=DESTROY_PIT_Y; c[1]=UI_TIMER_Y_LIMIT; c[2]=UI_SCORE_Y_LIMIT;
    std::cout<<"[Metal] Radar initialized\n";
    return true;
}

void run_radar_on_pair(id<MTLTexture> cur,id<MTLTexture> prev){
    @autoreleasepool {
        id<MTLCommandBuffer> cmd=[g_commandQueue commandBuffer];
        id<MTLComputeCommandEncoder> enc=[cmd computeCommandEncoder];
        [enc setComputePipelineState:g_radarPipeline];
        [enc setTexture:cur atIndex:0]; [enc setTexture:prev atIndex:1]; [enc setTexture:g_debugTexture atIndex:2];
        [enc setBuffer:g_constantsBuffer offset:0 atIndex:0];
        MTLSize thr=MTLSizeMake(RADAR_WIDTH,RADAR_HEIGHT,1), tpt=MTLSizeMake(8,8,1);
        [enc dispatchThreads:thr threadsPerThreadgroup:tpt]; [enc endEncoding]; [cmd commit]; [cmd waitUntilCompleted];
    }
}

id<MTLTexture> cv_to_texture(const cv::Mat& bgr){
    cv::Mat rgba; cv::cvtColor(bgr,rgba,cv::COLOR_BGR2RGBA);
    MTLTextureDescriptor* d=[MTLTextureDescriptor texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm width:rgba.cols height:rgba.rows mipmapped:NO];
    d.usage=MTLTextureUsageShaderRead; id<MTLTexture> t=[g_device newTextureWithDescriptor:d];
    MTLRegion R=MTLRegionMake2D(0,0,rgba.cols,rgba.rows); [t replaceRegion:R mipmapLevel:0 withBytes:rgba.data bytesPerRow:rgba.step];
    return t;
}


