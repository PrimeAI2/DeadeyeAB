// ---------- v17.2 Desktop/multi-monitor safe coordinate helpers ----------
static inline CGFloat desktopTopMostY() {
    CGFloat top = -CGFLOAT_MAX;
    for (NSScreen* s in [NSScreen screens]) {
        top = std::max(top, NSMaxY(s.frame)); // Cocoa coords (bottom origin)
    }
    return top; // highest Y across the desktop in Cocoa coord space
}

static inline CGFloat toEventY_FromTop(CGFloat topY) {
    return desktopTopMostY() - topY;
}

static inline CGFloat cocoaOriginY_FromTop(CGFloat topY, CGFloat height) {
    return desktopTopMostY() - (topY + height);
}

// v17.2 Window info lookup
struct WindowInfo { CGRect rect; pid_t pid; uint64_t wid; bool valid; };

static WindowInfo find_window_info(const char* title) {
    WindowInfo out{{0,0,0,0},0,0,false};
    CFArrayRef wl = CGWindowListCopyWindowInfo(
        kCGWindowListOptionOnScreenOnly | kCGWindowListExcludeDesktopElements,
        kCGNullWindowID);
    if (!wl) return out;

    CFStringRef tRef = CFStringCreateWithCString(kCFAllocatorDefault, title, kCFStringEncodingUTF8);
    CFIndex n = CFArrayGetCount(wl);
    for (CFIndex i=0;i<n;i++) {
        auto info = (CFDictionaryRef)CFArrayGetValueAtIndex(wl,i);
        CFStringRef name = (CFStringRef)CFDictionaryGetValue(info, kCGWindowName);
        if (!name || !CFEqual(name, tRef)) continue;

        CFDictionaryRef bdict = (CFDictionaryRef)CFDictionaryGetValue(info, kCGWindowBounds);
        CGRect r = CGRectZero; if (bdict) CGRectMakeWithDictionaryRepresentation(bdict, &r);

        CFNumberRef pidNum = (CFNumberRef)CFDictionaryGetValue(info, kCGWindowOwnerPID);
        int pid=0; if (pidNum) CFNumberGetValue(pidNum, kCFNumberIntType, &pid);

        CFNumberRef widNum = (CFNumberRef)CFDictionaryGetValue(info, kCGWindowNumber);
        long long wid=0; if (widNum) CFNumberGetValue(widNum, kCFNumberLongLongType, &wid);

        out.rect=r; out.pid=(pid_t)pid; out.wid=(uint64_t)wid; out.valid=true;
        break;
    }
    CFRelease(tRef); CFRelease(wl); return out;
}

