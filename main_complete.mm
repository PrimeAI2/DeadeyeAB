static NSImage* nsimage_from_bgr(const cv::Mat& bgr) {
    if (bgr.empty()) return nil;
    cv::Mat rgba; cv::cvtColor(bgr, rgba, cv::COLOR_BGR2RGBA);
    const int w = rgba.cols, h = rgba.rows;
    const size_t stride = rgba.step;
    CGColorSpaceRef cs = CGColorSpaceCreateDeviceRGB();
    CFDataRef data = CFDataCreate(kCFAllocatorDefault, (const UInt8*)rgba.data, h * stride);
    CGDataProviderRef prov = CGDataProviderCreateWithCFData(data);
    CGImageRef img = CGImageCreate(w, h, 8, 32, stride, cs,
                                     kCGBitmapByteOrderDefault | kCGImageAlphaPremultipliedLast,
                                     prov, nullptr, false, kCGRenderingIntentDefault);
    NSImage* nsimg = [[NSImage alloc] initWithCGImage:img size:NSMakeSize(w,h)];
    CGImageRelease(img); CGDataProviderRelease(prov); CFRelease(data); CGColorSpaceRelease(cs);
    return nsimg;
}

