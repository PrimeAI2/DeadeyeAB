// v14.2 Note: This function now receives the METAL RADAR output (debugMat)
static void debug_draw_and_show(const cv::Mat& debugMat, const std::string& status) {
    cv::Mat vis;
    if (debugMat.empty()) {
        vis = cv::Mat(g_dbgH, g_dbgW, CV_8UC3, cv::Scalar(0,0,0));
    } else {
        // debugMat is 302x655 (RADAR_W x RADAR_H)
        double sx = (double)g_dbgW / debugMat.cols;
        double sy = (double)g_dbgH / debugMat.rows;
        double s = std::min(sx, sy);
        int nw = std::max(1, (int)std::round(debugMat.cols * s));
        int nh = std::max(1, (int)std::round(debugMat.rows * s));
        
        cv::Mat resizedMat;
        cv::resize(debugMat, resizedMat, cv::Size(nw,nh), 0, 0, cv::INTER_NEAREST); // Use INTER_NEAREST for sharp radar pixels
        
        // Ensure vis is 3-channel BGR for putText
        if (resizedMat.channels() == 4) {
            cv::cvtColor(resizedMat, vis, cv::COLOR_BGRA2BGR);
        } else if (resizedMat.channels() == 1) {
            cv::cvtColor(resizedMat, vis, cv::COLOR_GRAY2BGR);
        } else {
            vis = resizedMat.clone();
        }

        if (nw < g_dbgW || nh < g_dbgH) {
            cv::copyMakeBorder(vis, vis, 0, g_dbgH-nh, 0, g_dbgW-nw, cv::BORDER_CONSTANT, cv::Scalar(0,0,0));
        }
    }

    if (!status.empty()) {
        cv::putText(vis, status, {10, 24}, cv::FONT_HERSHEY_SIMPLEX, 0.6, cv::Scalar(255,255,255), 1, cv::LINE_AA);
    }

    NSImage* nsimg = nsimage_from_bgr(vis);
    g_debugView.image = nsimg;
}

