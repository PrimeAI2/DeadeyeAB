TrajectoryPrediction predict_full_trajectory(const RockState& r){
    TrajectoryPrediction pred; 
    float x=r.center.x, y=r.center.y, vx=r.velocity.x, vy=r.velocity.y; 
    const float dt=1.0f/60.0f, T=10.0f; 
    float t=0.0f; 
    pred.min_x=x; pred.max_x=x; 
    int b=0, B=50;
    
    while(t<T && b<B){
        vy+=GRAVITY*dt; 
        x+=vx*dt; 
        y+=vy*dt; 
        pred.min_x=std::min(pred.min_x,x); 
        pred.max_x=std::max(pred.max_x,x);
        
        if(x<=0.0f){ 
            x=0.0f; 
            vx=std::abs(vx)*ROCK_BOUNCE_DAMPING; 
            pred.bounces.push_back({x,y,t,BouncePoint::WALL_LEFT}); 
            b++; 
        }
        if(x>=RADAR_WIDTH){ 
            x=RADAR_WIDTH; 
            vx=-std::abs(vx)*ROCK_BOUNCE_DAMPING; 
            pred.bounces.push_back({x,y,t,BouncePoint::WALL_RIGHT}); 
            b++; 
        }
        if(y>=CANNON_GROUND_Y){ 
            y=CANNON_GROUND_Y; 
            vy=-std::abs(vy)*ROCK_BOUNCE_DAMPING; 
            pred.bounces.push_back({x,y,t,BouncePoint::GROUND}); 
            pred.ground_crossings.push_back({t,x}); 
            b++; 
            if(std::abs(vy)<10.0f){ 
                pred.is_stable=true; 
                break; 
            } 
        }
        t+=dt;
    } 
    return pred;
}

void check_bullet_hits(){
    for(auto& b: g_bullets){
        if(!b.active) continue;
        for(auto& [id,r]: g_rock_database){
            CollisionBox bb={b.x-5,b.x+5,b.y-10,b.y+10};
            if(bb.overlaps(r.get_collision_box())){ 
                r.hp--; 
                b.active=false;
                if(r.hp<=0){
                    g_last_destroyed_hp=r.original_hp;
                    // Split logic: Large and Medium rocks split, Small rocks don't
                    if((r.size == RockSize::LARGE || r.size == RockSize::MEDIUM) && !r.is_split_child){
                        g_pending_split_children=2;
                        g_split_child_hp=r.original_hp/2;
                    }
                }
                break;
            }
        }
    }
}

// Helper: Determine rock size from bounding box
RockSize getRockSize(const cv::Rect& bbox) {
    int size = std::max(bbox.width, bbox.height);
    if (size < 100) {
        return RockSize::SMALL;      // ~50px
    } else if (size < 215) {
        return RockSize::MEDIUM;     // ~175px
    } else {
        return RockSize::LARGE;      // ~250px
    }
}

void update_rock_database(cv::Mat& radar,double ts,float dt){
    std::vector<cv::Mat> ch(4); cv::split(radar,ch);
    cv::Mat red=ch[2], green=ch[1];
    std::vector<std::vector<cv::Point>> cont;
    cv::findContours(red,cont,cv::RETR_EXTERNAL,cv::CHAIN_APPROX_SIMPLE);

    std::vector<RockState> det;
    for(const auto& c: cont){
        double area = cv::contourArea(c);

        // Filter 1: Area must be at least 1000px (small rock ~2500px)
        if(area < 1000.0) continue;

        // Filter 2: Area can't be huge (large rock ~62500px, add margin)
        if(area > 70000.0) continue;

        cv::Rect bb=cv::boundingRect(c);

        // Filter 3: Bounding box size must be reasonable (30-300px)
        int maxDim = std::max(bb.width, bb.height);
        if(maxDim < 30 || maxDim > 300) continue;

        // Filter 4: Must be roughly square (aspect ratio 0.5 to 2.0)
        float aspect = static_cast<float>(bb.width) / std::max(1, bb.height);
        if(aspect < 0.5f || aspect > 2.0f) continue;

        // Filter 5: Ignore things near cannon level (Y > 580)
        cv::Point2f center(bb.x+bb.width/2.0f, bb.y+bb.height/2.0f);
        if(center.y > 580.0f) continue;

        // Passed all filters - this is a real rock
        int hpix=cv::countNonZero(green(bb));
        RockState d;
        d.bbox=bb;
        d.center=center;
        d.last_seen=ts;
        d.hp=(hpix>5)? g_last_destroyed_hp+1 : 1;
        d.size = getRockSize(bb);  // Classify size
        det.push_back(d);
    }
    
    std::map<int,RockState> next; 
    std::vector<char> m(det.size(),0);
    
    for(auto& [id,o]: g_rock_database){
        float best=100.f; int k=-1;
        for(size_t i=0;i<det.size();++i){ 
            if(m[i]) continue; 
            float dist=cv::norm(det[i].center - o.center); 
            if(dist<best){ 
                best=dist; 
                k=(int)i; 
            } 
        }
        if(k>=0){
            m[k]=1; 
            RockState& r=det[k];
            if(dt>0.001f){ 
                r.velocity.x=(r.center.x-o.center.x)/dt; 
                r.velocity.y=(r.center.y-o.center.y)/dt; 
            } else {
                r.velocity=o.velocity;
            }
            r.id=o.id;
            r.hp=o.hp;
            r.original_hp=o.original_hp;
            r.is_tracked=true;
            r.is_split_child=o.is_split_child;
            // Note: r.size was already set by getRockSize() above, keep the fresh measurement
            r.type=(r.center.y < FALLING_THRESHOLD_Y)? 
                   RockState::Type::FALLING : 
                   (r.center.y >= CANNON_GROUND_Y-30? RockState::Type::LANDED : RockState::Type::FALLING);
            TrajectoryPrediction t=predict_full_trajectory(r);
            if(!t.ground_crossings.empty()){ 
                r.time_to_ground=t.ground_crossings[0].first; 
                r.predicted_x=t.ground_crossings[0].second; 
            } else { 
                r.time_to_ground=999.f; 
                r.predicted_x=r.center.x; 
            }
            next[r.id]=r;
        } else { 
            g_last_destroyed_hp=o.hp; 
        }
    }
    
    for(size_t i=0;i<det.size();++i){
        if(m[i]) continue;
        RockState r=det[i]; 
        r.id=g_next_rock_id++; 
        r.velocity=cv::Point2f(0,0); 
        r.is_tracked=false; 
        r.type=RockState::Type::FALLING;
        
        if(g_pending_split_children>0){ 
            r.hp=g_split_child_hp; 
            r.original_hp=g_split_child_hp; 
            r.is_split_child=true; 
            g_pending_split_children--; 
        } else { 
            r.hp=g_last_destroyed_hp+1; 
            r.original_hp=r.hp; 
            r.is_split_child=false; 
        }
        
        TrajectoryPrediction t=predict_full_trajectory(r);
        if(!t.ground_crossings.empty()){ 
            r.time_to_ground=t.ground_crossings[0].first; 
            r.predicted_x=t.ground_crossings[0].second; 
        } else { 
            r.time_to_ground=999.f; 
            r.predicted_x=r.center.x; 
        }
        next[r.id]=r;
    }
    g_rock_database.swap(next);
}

std::vector<SafeZone> find_safe_camping_zones(){
    const int W=RADAR_WIDTH; 
    const float HZN=5.0f; 
    const int SL=50; 
    const float DT=HZN/SL;
    
    std::vector<std::vector<bool>> occ(SL,std::vector<bool>(W,false));
    
    for(const auto& [id,r]: g_rock_database){
        TrajectoryPrediction tr=predict_full_trajectory(r);
        for(const auto& p: tr.ground_crossings){
            float tt=p.first, xx=p.second; 
            if(tt>HZN) continue;
            int s=(int)(tt/DT); 
            if(s>=SL) continue;
            int xmin=std::max(0,(int)(xx-CANNON_WIDTH/2.0f)); 
            int xmax=std::min(W,(int)(xx+CANNON_WIDTH/2.0f));
            for(int x=xmin;x<xmax;x++) occ[s][x]=true;
        }
    }
    
    std::vector<bool> safe(W,true);
    for(int x=0;x<W;x++){ 
        for(int t=0;t<SL;t++){ 
            if(occ[t][x]){ 
                safe[x]=false; 
                break; 
            } 
        } 
    }
    
    std::vector<SafeZone> zones; 
    int st=-1;
    for(int x=CANNON_WIDTH/2;x<W-CANNON_WIDTH/2;x++){
        if(safe[x]){ 
            if(st==-1) st=x; 
        } else { 
            if(st!=-1){ 
                SafeZone z; 
                z.x_min=st; 
                z.x_max=x; 
                z.x_center=(z.x_min+z.x_max)/2.0f; 
                z.width=z.x_max-z.x_min; 
                z.is_permanent=true; 
                z.safe_until=999.0; 
                if(z.width>=MIN_SAFE_GAP) zones.push_back(z); 
                st=-1; 
            } 
        }
    }
    return zones;
}

SafeZone find_best_safe_zone(float cx,const std::vector<SafeZone>& z){
    if(z.empty()) return {cx,cx-10,cx+10,20,false,0.0};
    const SafeZone* best=nullptr; 
    float md=1e9f;
    for(const auto& s: z){ 
        float d=std::abs(s.x_center-cx); 
        if(d<md){ 
            md=d; 
            best=&s; 
        } 
    }
    return best?*best:z[0];
}

BotDecision decide(float cannon_x_rel){
    BotDecision d;
    auto zones=find_safe_camping_zones();
    
    // Imminent threat check
    bool imminent=false;
    for(const auto& [id,r]: g_rock_database){
        if(r.time_to_ground<PANIC_TIME){
            float dist=std::abs(r.predicted_x-cannon_x_rel);
            if(dist<CANNON_WIDTH){ 
                imminent=true; 
                break; 
            }
        }
    }
    
    if(imminent){
        d.priority="P0_EMERGENCY"; 
        d.strategy="DODGE"; 
        d.decision="EMERGENCY_MOVE";
        auto best=find_best_safe_zone(cannon_x_rel,zones);
        d.target_x_rel=best.x_center;
        return d;
    }

    int total=(int)g_rock_database.size();
    if(total<LOW_THREAT_THRESHOLD && zones.size()>3){
        d.priority="P1_OFFENSE"; 
        d.strategy="HUNT";
        RockState* w=nullptr; 
        int mh=9999;
        for(auto& [id,r]: g_rock_database){ 
            if(r.is_falling() && r.hp<mh){ 
                mh=r.hp; 
                w=&r; 
            } 
        }
        if(w){ 
            d.decision="CHASE_WEAKEST"; 
            d.target_x_rel=w->predicted_x; 
        } else { 
            d.strategy="CAMP"; 
            d.decision="NO_TARGETS"; 
            auto best=find_best_safe_zone(cannon_x_rel,zones); 
            d.target_x_rel=best.x_center; 
        }
    } else {
        d.priority="P1_DEFENSE"; 
        d.strategy="CAMP";
        auto best=find_best_safe_zone(cannon_x_rel,zones);
        bool in=false; 
        for(const auto& z: zones){ 
            if(cannon_x_rel>=z.x_min && cannon_x_rel<=z.x_max){ 
                in=true; 
                break; 
            } 
        }
        if(in){ 
            d.decision="STAY_IN_ZONE"; 
            d.target_x_rel=cannon_x_rel; 
        } else { 
            d.decision="MOVE_TO_SAFE_ZONE"; 
            d.target_x_rel=best.x_center; 
        }
    }
    return d;
}

// v14.2 Cannon Watchdog (Ported)
void ensure_drag_control(float observed_x_rel, float desired_x_rel, bool imminent){
    // Detect "no movement"
    if(g_last_observed_x_rel>=0 && std::abs(observed_x_rel - g_last_observed_x_rel) <= 2.0f){
        g_no_movement_frames++;
    } else {
        g_no_movement_frames = 0;
    }
    g_last_observed_x_rel = observed_x_rel;

    bool far_from_target = std::abs(desired_x_rel - observed_x_rel) > 15.0f;
    bool rocks_exist = !g_rock_database.empty();

    if((imminent || (rocks_exist && g_no_movement_frames > 45) || (far_from_target && g_no_movement_frames > 20)) && g_rehold_cooldown==0){
        // v14.2: We need the absolute Y of the cannon
        // This is fine, as g_cannon_y_abs is set by click_and_hold.
        release_mouse();
        std::this_thread::sleep_for(std::chrono::milliseconds(20));
        click_and_hold(g_windowRect.origin.x + observed_x_rel, g_cannon_y_abs);
        g_rehold_cooldown = 30; // ~1.0s at 30fps
        std::cerr<<"[RECOVER] Re-held at observed X="<<observed_x_rel<<"\n";
    }
    if(g_rehold_cooldown>0) g_rehold_cooldown--;
}


