struct ButtonCand{ cv::Rect r; cv::Point c; double area; };

static std::vector<ButtonCand> find_orange_buttons(const cv::Mat& bgr){
    std::vector<ButtonCand> out; if(bgr.empty()) return out;
    cv::Mat hsv,mask; cv::cvtColor(bgr,hsv,cv::COLOR_BGR2HSV);
    cv::inRange(hsv, ORANGE_LOW, ORANGE_HIGH, mask); // Use v14.2's ORANGE
    cv::morphologyEx(mask,mask,cv::MORPH_CLOSE,cv::getStructuringElement(cv::MORPH_RECT, cv::Size(9,9)));
    std::vector<std::vector<cv::Point>> cnt; cv::findContours(mask,cnt,cv::RETR_EXTERNAL,cv::CHAIN_APPROX_SIMPLE);
    for(const auto& c: cnt){
        double a=cv::contourArea(c); if(a<800) continue;
        cv::Rect r=cv::boundingRect(c);
        if(r.width > bgr.cols*0.9 || r.height > bgr.rows*0.4) continue;
        out.push_back({r, cv::Point(r.x+r.width/2, r.y+r.height/2), a});
    }
    std::sort(out.begin(),out.end(),[](auto&A,auto&B){return A.c.y < B.c.y;}); // top→bottom
    return out;
}

static cv::Point find_cannon_start(const cv::Mat& bgr){
    if(bgr.empty()) return {-1,-1};
    cv::Mat hsv,mask; cv::cvtColor(bgr,hsv,cv::COLOR_BGR2HSV);
    cv::inRange(hsv, CANNON_HSV_LOW, CANNON_HSV_HIGH, mask);
    int yMin=(int)std::floor(bgr.rows*0.60);
    if(yMin < mask.rows) mask.rowRange(0,yMin).setTo(0);
    cv::morphologyEx(mask,mask,cv::MORPH_CLOSE,cv::getStructuringElement(cv::MORPH_RECT, cv::Size(7,7)));
    std::vector<std::vector<cv::Point>> cnt; cv::findContours(mask,cnt,cv::RETR_EXTERNAL,cv::CHAIN_APPROX_SIMPLE);
    double bestA=0; cv::Rect best;
    for(const auto& c: cnt){
        double a=cv::contourArea(c); if(a<120 || a>12000) continue;
        if(a>bestA){ bestA=a; best=cv::boundingRect(c); }
    }
    if(best.width==0) return {-1,-1};
    // v14.2 used a +30 offset, v17.2 has one. Let's keep v17.2's.
    return {best.x + best.width/2, best.y + best.height/2 + 30};
}

// v14.2 Live Cannon Tracker (Ported)
float track_cannon_live(const cv::Mat& f){
    int y0=(int)(f.rows*0.60); cv::Rect roi(0,y0,f.cols,f.rows-y0); if(roi.height<=0) return -1;
    cv::Mat c=f(roi).clone();
    cv::Mat hsv,mask; cv::cvtColor(c,hsv,cv::COLOR_BGR2HSV); cv::inRange(hsv,CANNON_HSV_LOW,CANNON_HSV_HIGH,mask);
    cv::morphologyEx(mask,mask,cv::MORPH_OPEN,cv::getStructuringElement(cv::MORPH_RECT,{5,5}));
    cv::morphologyEx(mask,mask,cv::MORPH_CLOSE,cv::getStructuringElement(cv::MORPH_RECT,{7,7}));
    std::vector<std::vector<cv::Point>> cnt; cv::findContours(mask,cnt,cv::RETR_EXTERNAL,cv::CHAIN_APPROX_SIMPLE);
    if(cnt.empty()) return -1;
    double bestA=0; cv::Rect best;
    for(const auto& cc: cnt){
        cv::Rect r=cv::boundingRect(cc);
        if(r.height < 20 || r.width < 20) continue;
        double a=cv::contourArea(cc);
        if(a>bestA){ bestA=a; best=r; }
    }
    if(bestA<=0) return -1;
    float cx = best.x + best.width/2.0f;
    return cx;
}


